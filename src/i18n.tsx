export type TranslationKey = keyof typeof translations.en;

interface I18nContextValue {
  t: (key: TranslationKey) => string;
  language: Language;
  setLanguage: (lang: Language) => void;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children, language, setLanguage }: { children: ReactNode; language: Language; setLanguage: (l: Language) => void }) {
  const t = useCallback(
    (key: TranslationKey): string => {
      return translations[language][key] ?? translations.en[key] ?? key;
    },
    [language],
  );

  return <I18nContext value={{ t, language, setLanguage }}>{children}</I18nContext>;
}

export function useT() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useT must be inside I18nProvider');
  return ctx;
}

export function useLanguageState(initial: Language = 'en') {
  return useState<Language>(initial);
}
